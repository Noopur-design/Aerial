export const getProduct = (slug) => products.find((p) => p.slug === slug);

export const productsBy = {
  gender: (g) => products.filter((p) => p.gender === g),
  collection: (c) => products.filter((p) => p.collections.includes(c)),
  newIn: () =>
    products
      .filter((p) => ['New', 'Just Dropped', 'Limited Edition'].includes(p.badge) || p.added >= '2025-09-01')
      .sort((a, b) => b.added.localeCompare(a.added)),
  bestsellers: () => [...products].sort((a, b) => b.popularity - a.popularity),
};

export function relatedProducts(product, count = 4) {
  const score = (p) =>
    (p.gender === product.gender ? 2 : 0) +
    p.collections.filter((c) => product.collections.includes(c)).length * 2 +
    (p.type !== product.type ? 1 : 0);
  return products
    .filter((p) => p.slug !== product.slug)
    .sort((a, b) => score(b) - score(a) || b.popularity - a.popularity)
    .slice(0, count);
}

